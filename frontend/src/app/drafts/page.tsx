"use client";

import React, { useEffect, useState, Suspense } from "react";
import Link from "next/link";
import { useSearchParams } from "next/navigation";
import {
  FileCheck2,
  CheckCircle2,
  XCircle,
  Send,
  Edit3,
  ShieldCheck,
  AlertTriangle,
  Building2,
  Sparkles,
  Save,
  Lock,
} from "lucide-react";
import { DraftAPI } from "@/lib/api";
import { EmailDraft } from "@/types";
import { formatDate } from "@/lib/utils";

function DraftsApprovalContent() {
  const searchParams = useSearchParams();
  const campaignIdFilter = searchParams.get("campaignId");

  const [drafts, setDrafts] = useState<EmailDraft[]>([]);
  const [selectedDraft, setSelectedDraft] = useState<EmailDraft | null>(null);
  const [editSubject, setEditSubject] = useState("");
  const [editBody, setEditBody] = useState("");
  const [loading, setLoading] = useState(true);
  const [actionMessage, setActionMessage] = useState<{ type: "success" | "error"; text: string } | null>(null);

  async function loadDrafts() {
    try {
      const data = await DraftAPI.list(
        campaignIdFilter ? { campaignId: campaignIdFilter } : undefined
      );
      setDrafts(data);
      if (data.length > 0 && !selectedDraft) {
        selectDraftForReview(data[0]);
      } else if (selectedDraft) {
        const refreshed = data.find((d) => d._id === selectedDraft._id);
        if (refreshed) {
          selectDraftForReview(refreshed);
        }
      }
    } catch (err) {
      console.error(err);
    } finally {
      setLoading(false);
    }
  }

  useEffect(() => {
    loadDrafts();
  }, [campaignIdFilter]);

  function selectDraftForReview(draft: EmailDraft) {
    setSelectedDraft(draft);
    setEditSubject(draft.subject);
    setEditBody(draft.body);
    setActionMessage(null);
  }

  async function handleSaveEdits() {
    if (!selectedDraft) return;
    try {
      const updated = await DraftAPI.update(selectedDraft._id, {
        subject: editSubject,
        body: editBody,
      });
      selectDraftForReview(updated);
      setActionMessage({
        type: "success",
        text: "Draft saved. Note: Previous approval was invalidated due to content modification to enforce security.",
      });
      loadDrafts();
    } catch (err: any) {
      setActionMessage({
        type: "error",
        text: err?.response?.data?.detail || "Failed to update draft.",
      });
    }
  }

  async function handleApprove() {
    if (!selectedDraft) return;
    try {
      await DraftAPI.approve(selectedDraft._id);
      setActionMessage({
        type: "success",
        text: "Draft explicitly approved and cryptographically hashed! Ready for secure Gmail delivery.",
      });
      loadDrafts();
    } catch (err: any) {
      setActionMessage({
        type: "error",
        text: err?.response?.data?.detail || "Approval failed.",
      });
    }
  }

  async function handleReject() {
    if (!selectedDraft) return;
    try {
      await DraftAPI.reject(selectedDraft._id);
      setActionMessage({
        type: "success",
        text: "Draft rejected and archived from the active send queue.",
      });
      loadDrafts();
    } catch (err: any) {
      setActionMessage({
        type: "error",
        text: err?.response?.data?.detail || "Rejection failed.",
      });
    }
  }

  async function handleSend() {
    if (!selectedDraft) return;
    try {
      const res = await DraftAPI.send(selectedDraft._id);
      setActionMessage({
        type: "success",
        text: `Email dispatched successfully! Delivery reference: ${res.deliveryResult?.providerMessageId || "Delivered"}`,
      });
      loadDrafts();
    } catch (err: any) {
      setActionMessage({
        type: "error",
        text: err?.response?.data?.detail || "Email delivery failed.",
      });
    }
  }

  return (
    <div className="max-w-7xl mx-auto space-y-6">
      {/* Page Header */}
      <div className="flex items-center justify-between">
        <div>
          <h1 className="text-2xl font-bold text-white flex items-center gap-2">
            <FileCheck2 className="w-6 h-6 text-primary" />
            Human-in-the-Loop Approval Queue
          </h1>
          <p className="text-sm text-slate-400">
            Every email draft generated by KORE requires explicit student review and cryptographic sign-off before sending.
          </p>
        </div>
      </div>

      {actionMessage && (
        <div
          className={`p-4 rounded-xl text-xs font-medium border flex items-center gap-2 ${
            actionMessage.type === "success"
              ? "bg-emerald-500/10 text-emerald-400 border-emerald-500/30"
              : "bg-destructive/10 text-destructive border-destructive/30"
          }`}
        >
          {actionMessage.type === "success" ? (
            <CheckCircle2 className="w-4 h-4 shrink-0" />
          ) : (
            <AlertTriangle className="w-4 h-4 shrink-0" />
          )}
          <span>{actionMessage.text}</span>
        </div>
      )}

      {/* Main Split Layout: Left Draft List, Right Editor */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 items-start">
        {/* Left Column: Drafts Selector */}
        <div className="lg:col-span-5 space-y-3">
          <div className="text-xs font-semibold text-muted uppercase tracking-wider px-1">
            Generated Drafts ({drafts.length})
          </div>

          {loading ? (
            <div className="p-8 text-center text-xs text-muted">Loading drafts...</div>
          ) : drafts.length === 0 ? (
            <div className="p-8 rounded-xl bg-surface border border-dashed border-border text-center text-xs text-muted">
              No drafts in queue. Execute a campaign to generate personalized outreach.
            </div>
          ) : (
            <div className="space-y-2.5 max-h-[750px] overflow-y-auto pr-1">
              {drafts.map((d) => {
                const isSelected = selectedDraft?._id === d._id;
                return (
                  <button
                    key={d._id}
                    onClick={() => selectDraftForReview(d)}
                    className={`w-full text-left p-4 rounded-xl border transition-all space-y-2 ${
                      isSelected
                        ? "bg-surface-card border-primary/50 shadow-glow"
                        : "bg-surface hover:bg-surface-card border-border"
                    }`}
                  >
                    <div className="flex items-center justify-between">
                      <div className="font-semibold text-white text-sm">
                        {d.recipientName}
                      </div>
                      <span
                        className={`text-[10px] px-2 py-0.5 rounded-full capitalize font-medium ${
                          d.approvalStatus === "approved"
                            ? "bg-emerald-500/15 text-emerald-400 border border-emerald-500/30"
                            : d.approvalStatus === "sent"
                            ? "bg-blue-500/15 text-blue-400 border border-blue-500/30"
                            : d.approvalStatus === "rejected"
                            ? "bg-destructive/15 text-destructive border border-destructive/30"
                            : "bg-amber-500/15 text-amber-400 border border-amber-500/30"
                        }`}
                      >
                        {d.approvalStatus.replace("_", " ")}
                      </span>
                    </div>

                    <div className="text-xs text-slate-300 font-medium">
                      {d.companyName} • <span className="text-muted">{d.recipientRole}</span>
                    </div>

                    <div className="text-xs text-slate-400 line-clamp-1 italic">
                      &quot;{d.subject}&quot;
                    </div>

                    <div className="text-[10px] text-muted flex items-center justify-between pt-1 border-t border-border/40">
                      <span>{d.recipientEmail}</span>
                      <span>{formatDate(d.createdAt)}</span>
                    </div>
                  </button>
                );
              })}
            </div>
          )}
        </div>

        {/* Right Column: Draft Editor & Approval Controls */}
        <div className="lg:col-span-7">
          {selectedDraft ? (
            <div className="p-6 rounded-2xl bg-surface border border-border shadow-card space-y-6">
              {/* Recipient & Status Bar */}
              <div className="flex items-start justify-between pb-4 border-b border-border">
                <div>
                  <div className="text-sm font-bold text-white flex items-center gap-2">
                    {selectedDraft.recipientName}
                    <span className="text-xs font-normal text-muted">
                      ({selectedDraft.recipientRole})
                    </span>
                  </div>
                  <div className="text-xs text-slate-400 mt-0.5 flex items-center gap-2">
                    <span className="text-primary font-medium">{selectedDraft.companyName}</span>
                    <span>•</span>
                    <span className="font-mono text-slate-300">{selectedDraft.recipientEmail}</span>
                  </div>
                </div>

                <div className="text-right">
                  <span
                    className={`inline-block text-xs px-2.5 py-1 rounded-lg capitalize font-medium ${
                      selectedDraft.approvalStatus === "approved"
                        ? "bg-emerald-500/15 text-emerald-400 border border-emerald-500/30"
                        : selectedDraft.approvalStatus === "sent"
                        ? "bg-blue-500/15 text-blue-400 border border-blue-500/30"
                        : selectedDraft.approvalStatus === "rejected"
                        ? "bg-destructive/15 text-destructive border border-destructive/30"
                        : "bg-amber-500/15 text-amber-400 border border-amber-500/30"
                    }`}
                  >
                    Status: {selectedDraft.approvalStatus.replace("_", " ")}
                  </span>
                  {selectedDraft.approvedContentHash && (
                    <div className="text-[10px] font-mono text-muted mt-1 truncate max-w-[200px]" title={selectedDraft.approvedContentHash}>
                      SHA256: {selectedDraft.approvedContentHash.slice(0, 16)}...
                    </div>
                  )}
                </div>
              </div>

              {/* Personalization Evidence Box */}
              {selectedDraft.personalizationEvidence && selectedDraft.personalizationEvidence.length > 0 && (
                <div className="p-3.5 rounded-xl bg-surface-card border border-border/80 text-xs space-y-1.5">
                  <div className="text-[11px] font-semibold text-primary uppercase tracking-wider flex items-center gap-1.5">
                    <Sparkles className="w-3.5 h-3.5" /> Personalization Evidence
                  </div>
                  <ul className="list-disc list-inside space-y-0.5 text-slate-300">
                    {selectedDraft.personalizationEvidence.map((ev, i) => (
                      <li key={i}>{ev}</li>
                    ))}
                  </ul>
                </div>
              )}

              {/* Subject Editor */}
              <div className="space-y-1.5">
                <label className="text-xs font-semibold text-slate-300">
                  Subject Line
                </label>
                <input
                  type="text"
                  value={editSubject}
                  disabled={selectedDraft.approvalStatus === "sent"}
                  onChange={(e) => setEditSubject(e.target.value)}
                  className="w-full px-3.5 py-2.5 rounded-xl bg-surface-card border border-border text-white text-sm focus:outline-none focus:border-primary transition-colors disabled:opacity-50"
                />
              </div>

              {/* Email Body Editor */}
              <div className="space-y-1.5">
                <label className="text-xs font-semibold text-slate-300 flex items-center justify-between">
                  <span>Email Body</span>
                  <span className="text-[11px] text-muted">
                    {editBody.trim().split(/\s+/).length} words
                  </span>
                </label>
                <textarea
                  rows={9}
                  value={editBody}
                  disabled={selectedDraft.approvalStatus === "sent"}
                  onChange={(e) => setEditBody(e.target.value)}
                  className="w-full p-3.5 rounded-xl bg-surface-card border border-border text-white text-sm font-sans leading-relaxed focus:outline-none focus:border-primary transition-colors disabled:opacity-50"
                />
                <p className="text-[11px] text-muted">
                  Rule: Editing content will invalidate existing approval and require a fresh sign-off to ensure integrity.
                </p>
              </div>

              {/* Action Buttons Row */}
              <div className="flex flex-wrap items-center justify-between gap-3 pt-4 border-t border-border">
                <div className="flex items-center gap-2">
                  <button
                    onClick={handleSaveEdits}
                    disabled={selectedDraft.approvalStatus === "sent"}
                    className="flex items-center gap-1.5 px-3.5 py-2 rounded-xl bg-surface-card hover:bg-surface-hover border border-border text-xs font-medium text-slate-200 transition-colors disabled:opacity-50"
                  >
                    <Save className="w-3.5 h-3.5" /> Save Edits
                  </button>

                  <button
                    onClick={handleReject}
                    disabled={selectedDraft.approvalStatus === "sent"}
                    className="flex items-center gap-1.5 px-3.5 py-2 rounded-xl bg-destructive/10 hover:bg-destructive/20 border border-destructive/30 text-xs font-medium text-destructive transition-colors disabled:opacity-50"
                  >
                    <XCircle className="w-3.5 h-3.5" /> Reject
                  </button>
                </div>

                <div className="flex items-center gap-3">
                  <button
                    onClick={handleApprove}
                    disabled={selectedDraft.approvalStatus === "approved" || selectedDraft.approvalStatus === "sent"}
                    className="flex items-center gap-1.5 px-4 py-2 rounded-xl bg-emerald-600 hover:bg-emerald-500 text-white text-xs font-medium transition-colors disabled:opacity-50"
                  >
                    <ShieldCheck className="w-4 h-4" />
                    {selectedDraft.approvalStatus === "approved" ? "Approved" : "Approve Draft"}
                  </button>

                  <button
                    onClick={handleSend}
                    disabled={selectedDraft.approvalStatus !== "approved"}
                    className="flex items-center gap-2 px-5 py-2 rounded-xl bg-primary hover:bg-primary-hover disabled:opacity-40 text-white text-xs font-medium shadow-glow transition-all"
                  >
                    <Send className="w-3.5 h-3.5" />
                    Send via Gmail
                  </button>
                </div>
              </div>
            </div>
          ) : (
            <div className="p-12 rounded-2xl bg-surface border border-dashed border-border text-center text-xs text-muted">
              Select an email draft from the left panel to review, edit, or approve.
            </div>
          )}
        </div>
      </div>
    </div>
  );
}

export default function DraftsApprovalPage() {
  return (
    <Suspense fallback={<div className="p-12 text-center text-xs text-muted">Loading approval queue...</div>}>
      <DraftsApprovalContent />
    </Suspense>
  );
}
