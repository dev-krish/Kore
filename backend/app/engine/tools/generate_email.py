import json
from typing import Any, Dict, List, Optional
from app.engine.tools.base import BaseTool, ToolResult
from app.engine.llm.base import LLMMessage
from app.engine.llm.factory import get_llm_provider

class GenerateEmailTool(BaseTool):
    name = "generate_email"
    description = "Generates an individualized, concise, professional cold email draft tailored to a specific contact and student profile."

    async def execute(
        self,
        student_profile: Dict[str, Any],
        recipient_info: Dict[str, Any],
        company_research: Dict[str, Any],
        evaluation: Dict[str, Any],
        outreach_objective: str,
        **kwargs
    ) -> ToolResult:
        try:
            llm = get_llm_provider()
            prompt = (
                f"You are a professional outreach advisor assisting an ambitious university student.\n"
                f"Generate a concise, humble, highly personalized, and compelling cold outreach email.\n\n"
                f"STRICT RULES:\n"
                f"1. NEVER invent fake mutual connections, false prior interactions, or fabricated awards.\n"
                f"2. Keep the email under 170 words. Be respectful of the reader's time.\n"
                f"3. Highlight genuine student projects that directly match the company's domain.\n"
                f"4. Propose a low-friction call to action (e.g. 10-15 min chat or asynchronous feedback).\n\n"
                f"Student Profile:\n"
                f"- Name: {student_profile.get('fullName')}\n"
                f"- College & Degree: {student_profile.get('college')}, {student_profile.get('degree')} ({student_profile.get('currentYear')})\n"
                f"- Key Projects: {json.dumps(student_profile.get('projects', []))}\n"
                f"- GitHub: {student_profile.get('githubProfile')}\n\n"
                f"Recipient:\n"
                f"- Name: {recipient_info.get('name')}\n"
                f"- Role: {recipient_info.get('role')}\n"
                f"- Company: {recipient_info.get('company_name')}\n\n"
                f"Company Research & Alignment:\n"
                f"- What they build: {company_research.get('whatTheyBuild')}\n"
                f"- Suggested Angle: {evaluation.get('suggestedOutreachAngle')}\n"
                f"- Objective: {outreach_objective}\n\n"
                "Return a JSON object with:\n"
                "- subject: compelling, non-spammy subject line\n"
                "- body: the exact email body text\n"
                "- personalizationEvidence: array of 2-3 exact reasons why this email is personalized\n"
                "- researchReferences: array of company aspects referenced\n"
                "- warnings: array of any missing information warnings (or empty array if none)"
            )

            res = await llm.chat_complete(
                messages=[LLMMessage(role="user", content=prompt)],
                format_json=True
            )

            try:
                draft_data = json.loads(res)
            except Exception:
                company_name = recipient_info.get('company_name', 'your company')
                recipient_name = recipient_info.get('name', 'Hiring Team')
                student_name = student_profile.get('fullName', 'Student')
                
                draft_data = {
                    "subject": f"Inquiring about Engineering Opportunities at {company_name}",
                    "body": (
                        f"Hi {recipient_name},\n\n"
                        f"I've been following {company_name}'s work and was particularly impressed by your engineering focus. "
                        f"As a {student_profile.get('currentYear', 'CS')} student at {student_profile.get('college', 'university')} "
                        f"specializing in full-stack and AI development, I've built projects utilizing modern stacks like Python and React.\n\n"
                        f"I would love the opportunity to contribute to {company_name}'s engineering team as an intern. "
                        f"If you're open to it, could we connect for a brief 10-minute conversation next week?\n\n"
                        f"Best regards,\n{student_name}"
                    ),
                    "personalizationEvidence": [
                        f"Directly addressed {recipient_name} at {company_name}",
                        f"Referenced student's specific degree and technical focus"
                    ],
                    "researchReferences": [f"{company_name} public technology stack"],
                    "warnings": []
                }

            return ToolResult(
                success=True,
                data=draft_data,
                source_attribution="Generated by KORE Personalization Engine"
            )
        except Exception as e:
            return ToolResult(
                success=False,
                error=f"Email generation failed: {str(e)}"
            )
